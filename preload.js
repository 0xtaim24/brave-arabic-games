  analyze: call('analyze'),
  exportRows: call('export'),
  models: call('models'),
  modelsAuto: call('models-auto'),
  listVoices: call('list-voices'),
  addVoice: call('add-voice'),
  removeVoice: call('remove-voice'),
  charactersList: call('characters-list'),
  characterNew: call('character-new'),
  characterImage: call('character-image'),
  characterReference: call('character-reference'),
  characterSave: call('character-save'),
  characterPreview: call('character-preview'),
  characterModelStatus: call('character-model-status'),
  characterModelDownload: call('character-model-download'),
  characterInstall: call('character-install'),
  characterTrial: call('character-trial'),
  characterTrialRestore: call('character-trial-restore'),
  characterDisable: call('character-disable'),
  micTranscribe: call('mic-transcribe'),
  micGameClip: call('mic-game-clip'),
  releaseMic: call('mic-release'),
  sttHardware: call('stt-hardware'),
  installSttGpu: call('install-stt-gpu'),
  apply: call('apply'),
  restore: call('restore'),
  getUser: call('get-user-overrides'),
  saveUser: call('save-user-overrides'),
  installUpdate: call('install-update'),
